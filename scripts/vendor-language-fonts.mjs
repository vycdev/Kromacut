// Maintenance-only importer. The application never contacts these providers.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'public/fonts/languages');
mkdirSync(output, { recursive: true });
const families = [
    'Noto Sans',
    'Noto Sans Devanagari',
    'Noto Sans Bengali',
    'Noto Sans JP',
    'Noto Sans SC',
];
const stylesheet = `https://fonts.googleapis.com/css2?${families.map((family) => `family=${family.replaceAll(' ', '+')}:wght@400..700`).join('&')}&display=swap`;
const headers = {
    'User-Agent':
        'Mozilla/5.0 AppleWebKit/537.36 (KHTML, like Gecko) Chrome/132.0.0.0 Safari/537.36',
};
async function fetchChecked(url) {
    const response = await fetch(url, { headers });
    if (!response.ok) throw new Error(`${response.status}: ${url}`);
    return response;
}
let css = await (await fetchChecked(stylesheet)).text();
const urls = [...new Set([...css.matchAll(/url\((https:[^)]+)\)/g)].map((match) => match[1]))];
const sources = [];
let index = 0;
await Promise.all(
    Array.from({ length: 6 }, async () => {
        while (index < urls.length) {
            const url = urls[index++];
            const bytes = Buffer.from(await (await fetchChecked(url)).arrayBuffer());
            const digest = createHash('sha256').update(bytes).digest('hex');
            const filename = `noto-${digest.slice(0, 16)}.woff2`;
            writeFileSync(path.join(output, filename), bytes);
            sources.push({ source: url, file: filename, sha256: digest });
        }
    })
);
for (const entry of sources) css = css.replaceAll(entry.source, `/fonts/languages/${entry.file}`);
const licenses = [];
for (const family of families) {
    const id = family.replaceAll(' ', '').toLowerCase();
    const source = `https://raw.githubusercontent.com/google/fonts/main/ofl/${id}/OFL.txt`;
    const text = await (await fetchChecked(source)).text();
    const filename = `${id}-OFL.txt`;
    writeFileSync(path.join(output, filename), text);
    licenses.push({ family, file: filename, source });
}
writeFileSync(
    path.join(root, 'src/styles/language-fonts.css'),
    `/* Generated by scripts/vendor-language-fonts.mjs. SIL OFL licenses in public/fonts/languages. */\n${css}`
);
writeFileSync(
    path.join(output, 'sources.json'),
    JSON.stringify(
        {
            downloaded: new Date().toISOString().slice(0, 10),
            stylesheet,
            licenses,
            files: sources.sort((a, b) => a.file.localeCompare(b.file)),
        },
        null,
        2
    ) + '\n'
);
console.log(
    `Vendored ${sources.length} Unicode subsets (${sources.reduce((n, entry) => n + readFileSync(path.join(output, entry.file)).length, 0)} bytes) for ${families.length} font families.`
);
